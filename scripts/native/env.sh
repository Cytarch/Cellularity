#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/../.." && pwd)"
CELLULARITY_NATIVE_SOURCE_DIR="${REPO_ROOT}/native"

: "${CELLULARITY_NATIVE_BUILD_DIR:=/tmp/cellularity_native_clang_build}"
: "${CCACHE_DIR:=/tmp/cellularity_ccache}"
: "${CELLULARITY_NATIVE_BUILD_TYPE:=Release}"
: "${CELLULARITY_NATIVE_PROFILE:=ON}"
: "${CELLULARITY_NATIVE_SANITIZERS:=OFF}"
: "${CELLULARITY_NATIVE_THREAD_SANITIZER:=OFF}"
: "${CELLULARITY_NATIVE_WARNINGS_AS_ERRORS:=OFF}"
: "${CELLULARITY_NATIVE_IPO:=ON}"
: "${CELLULARITY_NATIVE_OVERLAP_SCAN_ALGORITHM:=baseline}"
: "${CELLULARITY_NATIVE_RUNTIME_OVERLAP_SELECTION:=ON}"
: "${CELLULARITY_NATIVE_CELL_OWNED_SIGNAL_KERNEL:=ON}"
: "${CELLULARITY_NATIVE_EXPORT_COMPILE_COMMANDS:=OFF}"
: "${CELLULARITY_NATIVE_C_COMPILER:=clang}"
: "${CELLULARITY_NATIVE_CXX_COMPILER:=clang++}"
: "${CELLULARITY_NATIVE_LINKER:=lld}"
: "${CELLULARITY_NATIVE_AR:=llvm-ar}"
: "${CELLULARITY_NATIVE_RANLIB:=llvm-ranlib}"

if [[ -f "${CELLULARITY_NATIVE_BUILD_DIR}/CMakeCache.txt" ]] \
        && ! grep -Fqx \
            "CMAKE_HOME_DIRECTORY:INTERNAL=${CELLULARITY_NATIVE_SOURCE_DIR}" \
            "${CELLULARITY_NATIVE_BUILD_DIR}/CMakeCache.txt"; then
    source_path_key="$(
        printf '%s' "${CELLULARITY_NATIVE_SOURCE_DIR}" \
            | sha256sum \
            | cut -c1-12
    )"
    compatible_build_dir="${CELLULARITY_NATIVE_BUILD_DIR}_${source_path_key}"
    echo "Ignoring incompatible CMake cache at ${CELLULARITY_NATIVE_BUILD_DIR}; using ${compatible_build_dir}" >&2
    CELLULARITY_NATIVE_BUILD_DIR="${compatible_build_dir}"
fi

export CCACHE_DIR CELLULARITY_NATIVE_BUILD_DIR CELLULARITY_NATIVE_BUILD_TYPE
export CELLULARITY_NATIVE_PROFILE CELLULARITY_NATIVE_SANITIZERS
export CELLULARITY_NATIVE_THREAD_SANITIZER
export CELLULARITY_NATIVE_WARNINGS_AS_ERRORS CELLULARITY_NATIVE_IPO
export CELLULARITY_NATIVE_OVERLAP_SCAN_ALGORITHM
export CELLULARITY_NATIVE_RUNTIME_OVERLAP_SELECTION
export CELLULARITY_NATIVE_CELL_OWNED_SIGNAL_KERNEL
export CELLULARITY_NATIVE_EXPORT_COMPILE_COMMANDS
export CELLULARITY_NATIVE_C_COMPILER CELLULARITY_NATIVE_CXX_COMPILER
export CELLULARITY_NATIVE_LINKER CELLULARITY_NATIVE_AR CELLULARITY_NATIVE_RANLIB
