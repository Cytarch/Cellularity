#!/usr/bin/env bash
set -euo pipefail

source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/env.sh"

mkdir -p "${CCACHE_DIR}"

LAUNCHER_ARGS=()
if command -v ccache >/dev/null 2>&1; then
    LAUNCHER_ARGS+=(
        -DCMAKE_C_COMPILER_LAUNCHER=ccache
        -DCMAKE_CXX_COMPILER_LAUNCHER=ccache
    )
fi

cmake -S "${CELLULARITY_NATIVE_SOURCE_DIR}" \
      -B "${CELLULARITY_NATIVE_BUILD_DIR}" \
      -G Ninja \
      -DCMAKE_BUILD_TYPE="${CELLULARITY_NATIVE_BUILD_TYPE}" \
      -DCMAKE_C_COMPILER="${CELLULARITY_NATIVE_C_COMPILER}" \
      -DCMAKE_CXX_COMPILER="${CELLULARITY_NATIVE_CXX_COMPILER}" \
      -DCMAKE_AR="${CELLULARITY_NATIVE_AR}" \
      -DCMAKE_RANLIB="${CELLULARITY_NATIVE_RANLIB}" \
      -DCMAKE_C_COMPILER_AR="${CELLULARITY_NATIVE_AR}" \
      -DCMAKE_CXX_COMPILER_AR="${CELLULARITY_NATIVE_AR}" \
      -DCMAKE_C_COMPILER_RANLIB="${CELLULARITY_NATIVE_RANLIB}" \
      -DCMAKE_CXX_COMPILER_RANLIB="${CELLULARITY_NATIVE_RANLIB}" \
      -DCMAKE_EXE_LINKER_FLAGS="-fuse-ld=${CELLULARITY_NATIVE_LINKER}" \
      -DCMAKE_SHARED_LINKER_FLAGS="-fuse-ld=${CELLULARITY_NATIVE_LINKER}" \
      -DCELLULARITY_ENABLE_NATIVE_PROFILE="${CELLULARITY_NATIVE_PROFILE}" \
      -DCELLULARITY_ENABLE_SANITIZERS="${CELLULARITY_NATIVE_SANITIZERS}" \
      -DCELLULARITY_ENABLE_THREAD_SANITIZER="${CELLULARITY_NATIVE_THREAD_SANITIZER}" \
      -DCELLULARITY_WARNINGS_AS_ERRORS="${CELLULARITY_NATIVE_WARNINGS_AS_ERRORS}" \
      -DCELLULARITY_ENABLE_IPO="${CELLULARITY_NATIVE_IPO}" \
      -DCELLULARITY_DEFAULT_OVERLAP_SCAN_ALGORITHM="${CELLULARITY_NATIVE_OVERLAP_SCAN_ALGORITHM}" \
      -DCELLULARITY_ENABLE_RUNTIME_OVERLAP_SELECTION="${CELLULARITY_NATIVE_RUNTIME_OVERLAP_SELECTION}" \
      -DCELLULARITY_ENABLE_CELL_OWNED_SIGNAL_KERNEL="${CELLULARITY_NATIVE_CELL_OWNED_SIGNAL_KERNEL}" \
      -DCMAKE_EXPORT_COMPILE_COMMANDS="${CELLULARITY_NATIVE_EXPORT_COMPILE_COMMANDS}" \
      "${LAUNCHER_ARGS[@]}"
